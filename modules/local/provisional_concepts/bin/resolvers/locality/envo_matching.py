import pickle
import numpy as np
import torch
from pathlib import Path
from sentence_transformers import SentenceTransformer, CrossEncoder
from deep_translator import GoogleTranslator

from clients.envo_client import load_envo_cache, tree_search, semantic_search

REPO_ROOT = Path(__file__).parent.parent.parent
DATA_DIR = REPO_ROOT / "data"
ENVO_PATH = DATA_DIR / "envo_relevant_terms.json"  # input envo terms (generated by clients/envo_client.py)
CACHE_PATH = DATA_DIR / "envo_embeddings.pkl"  # cached embedding

RETRIEVE_K = 50          # how many candidates the embedding stage pulls
RERANK_SHORTLIST_K = 20  # how many of those actually get reranked
FINAL_TOP_K = 3

MAX_SYNONYMS_FOR_TEXT = 3

# we've decided to translate and then put it through an english only system cause it delivered way better results
# that means if there is a better multilingual option: both can be replaced with a multilingual embedder
# and the translation step can be removed
MODEL_NAME = "BAAI/bge-large-en-v1.5"
RERANK_MODEL_NAME = "cross-encoder/ms-marco-MiniLM-L-12-v2"

EXISTENCE_THRESHOLD = 0.7

model = None
reranker = None
envo_terms = None
envo_embeddings = None

def get_model():
    global model
    if model is None:
        device = "cuda" if torch.cuda.is_available() else "cpu"
        print(f"Using device: {device}")
        model = SentenceTransformer(MODEL_NAME, device=device)
    return model

translator = None
translation_cache = {}

def get_translator():
    global translator
    if translator is None:
        translator = GoogleTranslator(source="de", target="en")
    return translator

def translate_to_english(text):
    # instead of multilingual embedding, we use translation just because it delivers better results after testing
    if not text:
        return text
    if text in translation_cache:
        return translation_cache[text]
    try:
        translated = get_translator().translate(text)
        if not translated:
            translated = text
    except Exception as e:
        print(f"Translation failed for '{text}': {e}")
        translated = text
    translation_cache[text] = translated
    return translated

def get_reranker():
    global reranker
    if reranker is None:
        device = "cuda" if torch.cuda.is_available() else "cpu"
        print(f"Using device: {device}")
        # match probability should be between 0 and 1 (could be the case with the new model anyways but some got negative scores)
        reranker = CrossEncoder(
            RERANK_MODEL_NAME,
            device=device,
            activation_fn=torch.nn.Sigmoid(),
        )
    return reranker

def top_synonyms(term, limit=MAX_SYNONYMS_FOR_TEXT):
    # limiting helped reducing noise, e.g. "cultivated" had a pretty low score on "cultivated environment" before
    syns = term.get("synonyms") or []
    if not syns:
        return []
    seen = set()
    deduped = []
    for s in syns:
        key = s.lower().strip()
        if key and key not in seen:
            seen.add(key)
            deduped.append(s)
    deduped.sort(key=len)
    return deduped[:limit]

def build_envo_text(term):
    label = term.get("label", "")
    parts = [label, label]
    parts.extend(top_synonyms(term))
    return " ".join(p for p in parts if p)

def build_rerank_text(term):
    label = term.get("label", "")
    parts = [label, label]
    parts.extend(top_synonyms(term))
    desc = term.get("description", [])
    if desc:
        parts.append(desc[0] if isinstance(desc, list) else desc)
    return " ".join(p for p in parts if p)

def build_envo_embeddings(terms, cache_path=CACHE_PATH):
    texts = [build_envo_text(t) for t in terms]
    emb = get_model().encode(
        ["passage: " + t for t in texts],
        batch_size=64,
        convert_to_numpy=True,
        normalize_embeddings=True,
        show_progress_bar=True,
    )
    with open(cache_path, "wb") as f:
        pickle.dump(emb, f)
    return emb

def load_resources():
    global envo_terms, envo_embeddings
    if envo_terms is not None and envo_embeddings is not None:
        return
    envo_terms = load_envo_cache(ENVO_PATH)
    if CACHE_PATH.exists():
        with open(CACHE_PATH, "rb") as f:
            envo_embeddings = pickle.load(f)
    else:
        envo_embeddings = build_envo_embeddings(envo_terms)

def embedding_search(query, top_k=RETRIEVE_K):
    load_resources()
    vec = get_model().encode(
        ["query: " + query],
        convert_to_numpy=True,
        normalize_embeddings=True,
    )[0]
    scores = envo_embeddings @ vec
    idx = np.argsort(scores)[::-1][:top_k]
    return [{**envo_terms[i], "score": float(scores[i])} for i in idx]

def rerank(query, candidates):
    if not candidates:
        return []
    pairs = [[query, build_rerank_text(c)] for c in candidates]
    scores = get_reranker().predict(pairs)
    out = [{**c, "score": float(s), "rerank_score": float(s)} for c, s in zip(candidates, scores)]
    out.sort(key=lambda x: x["rerank_score"], reverse=True)
    return out


def match_envo(clean_field, threshold=EXISTENCE_THRESHOLD):
    if not clean_field:
        return {"method": None, "exists": False, "matches": []}

    query_en = translate_to_english(clean_field)

    hits = embedding_search(query_en, top_k=RETRIEVE_K)
    if not hits:
        return {"method": "embedding+rerank", "exists": False, "matches": [], "query_en": query_en}

    shortlist = hits[:RERANK_SHORTLIST_K]
    reranked = rerank(query_en, shortlist)

    top_score = reranked[0]["rerank_score"]
    if top_score < threshold:
        return {
            "method": "embedding+rerank",
            "exists": False,
            "matches": reranked[:FINAL_TOP_K],
            "top_score": top_score,
            "query_en": query_en,
        }

    return {
        "method": "embedding+rerank",
        "exists": True,
        "matches": reranked[:FINAL_TOP_K],
        "query_en": query_en,
    }